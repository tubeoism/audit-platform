#!/usr/bin/env bash
# Installed as /usr/local/sbin/audit-auth-key. Manages Auth__MasterKey in /etc/audit-master/master.env: the root of
# the keys that sign access tokens, encrypt TOTP secrets and hash stored tokens (ADR-0005).
#   sudo audit-auth-key --init          generate the key if there is none, then restart the master (idempotent)
#   sudo audit-auth-key --fingerprint   short fingerprint, safe to note anywhere (compare the offline copy against it)
#   sudo audit-auth-key --show          print the key ONCE so you can store an offline copy
#   sudo audit-auth-key --install       paste a key from your offline copy (new VM / disaster recovery). Input is hidden.
# Losing the key does not lose engagement data, but every user must enrol TOTP again and all sessions end.
set -euo pipefail
ENV_FILE=/etc/audit-master/master.env
NAME=Auth__MasterKey
[[ $EUID -eq 0 ]] || { echo "Run with sudo" >&2; exit 1; }
[[ -f "$ENV_FILE" ]] || { echo "$ENV_FILE not found; run bootstrap-vm.sh first" >&2; exit 1; }

current() { sed -n "s/^${NAME}=//p" "$ENV_FILE" | tail -n1; }
fp() { printf '%s' "$(current)" | sha256sum | cut -c1-16; }
write() {   # write KEY: replace or append the line, keeping the file root-owned 0600
  local tmp; tmp="$(mktemp /etc/audit-master/.master.env.XXXXXX)"; chmod 0600 "$tmp"
  grep -v "^${NAME}=" "$ENV_FILE" > "$tmp" || true
  printf '%s=%s\n' "$NAME" "$1" >> "$tmp"
  mv -f "$tmp" "$ENV_FILE"; chown root:root "$ENV_FILE"; chmod 0600 "$ENV_FILE"
}
restart() {
  systemctl restart audit-master.service; sleep 3
  curl -fsS -o /dev/null http://127.0.0.1:5080/healthz/ready && echo "Master OK." \
    || echo "Master chưa sẵn sàng, xem: journalctl -u audit-master -n 50"
}

case "${1:-}" in
  --init)
    if [[ -n "$(current)" ]]; then echo "Đã có khoá, fingerprint $(fp). Không thay đổi."; exit 0; fi
    write "$(head -c 32 /dev/urandom | base64 -w0)"
    echo "Đã tạo khoá xác thực, fingerprint $(fp)."
    echo "Việc tiếp theo: sudo audit-auth-key --show  rồi cất khoá ngoại tuyến, cùng chỗ với khoá backup."
    logger -t audit-auth-key "auth master key generated by ${SUDO_USER:-root}"
    restart ;;
  --fingerprint) [[ -n "$(current)" ]] || { echo "Chưa có khoá" >&2; exit 1; }; fp ;;
  --show)
    [[ -n "$(current)" ]] || { echo "Chưa có khoá; chạy --init trước" >&2; exit 1; }
    echo "Khoá xác thực (base64). Lưu ngoại tuyến: trình quản lý mật khẩu + bản in cất an toàn."
    echo "Mất khoá này = mọi người dùng phải cài lại TOTP và đăng nhập lại; dữ liệu engagement không mất."
    echo; current; echo
    echo "Fingerprint: $(fp)"
    logger -t audit-auth-key "auth master key displayed by ${SUDO_USER:-root}" ;;
  --install)
    [[ -n "$(current)" ]] && { read -rp "Đã có khoá (fingerprint $(fp)). Ghi đè sẽ vô hiệu mọi TOTP và phiên hiện có. Gõ YES: " ok; [[ "$ok" == YES ]] || exit 1; }
    read -rsp "Dán khoá base64: " k; echo
    [[ "$k" =~ ^[A-Za-z0-9+/]{43,}=*$ ]] && [[ "$(printf '%s' "$k" | base64 -d 2>/dev/null | wc -c)" -ge 32 ]] \
      || { echo "Khoá không hợp lệ (cần base64 của ít nhất 32 byte)" >&2; exit 1; }
    write "$k"
    echo "Đã cài khoá, fingerprint $(fp)"
    logger -t audit-auth-key "auth master key installed by ${SUDO_USER:-root}"
    restart ;;
  *) sed -n '2,8p' "$0"; exit 2 ;;
esac
